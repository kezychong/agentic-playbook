#!/usr/bin/env python3
"""Concat build for hermes-jarvis. Python stdlib only, no bundler, no npm.

    python3 scripts/build.py            write desktop/plugin.js (+ dashboard/mirror.html)
    python3 scripts/build.py --check    exit 1 when an output is missing or stale

desktop/plugin.js  = src/*.js in name order, EXCEPT 45-mirror.js (mirror only).
dashboard/mirror.html = dashboard/mirror.template.html with
    __JARVIS_THEME_CSS__  -> the resolved value of JARVIS_CSS from 10-theme.js
    __JARVIS_MIRROR_JS__  -> 10-theme.js + 35-assets.js + 40-scene.js + 45-mirror.js
The template is owned by WP-B; when it is absent the mirror step is skipped.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
BANNER = "// Generated by scripts/build.py from src/*.js — edit src/\n"

MIRROR_ONLY = "45-mirror.js"
MIRROR_PARTS = ["05-scope.js", "10-theme.js", "35-assets.js", "40-scene.js", "45-mirror.js"]


def warn(message: str) -> None:
    print(f"warning: {message}", file=sys.stderr)


def source_files() -> list[Path]:
    return [p for p in sorted(SRC.glob("*.js")) if p.name != MIRROR_ONLY]


def build_plugin() -> str:
    parts = [BANNER]
    for path in source_files():
        body = path.read_text(encoding="utf-8")
        check_imports(path.name, body)
        parts.append(f"\n// ─── {path.name} " + "─" * max(0, 58 - len(path.name)) + "\n")
        parts.append(body if body.endswith("\n") else body + "\n")
    return "".join(parts)


def check_imports(name: str, body: str) -> None:
    """Hard constraint: only 00-header.js imports, only 60-plugin.js exports."""
    for line in body.splitlines():
        if re.match(r"^import\s", line) and name != "00-header.js":
            raise SystemExit(f"error: {name} has a top-level import — only 00-header.js may import")
        if re.match(r"^export\s", line) and name != "60-plugin.js":
            raise SystemExit(f"error: {name} has a top-level export — only 60-plugin.js may export")


# --- mirror -----------------------------------------------------------------

TOKEN_RE = re.compile(r"^\s*([A-Za-z0-9_]+)\s*:\s*'([^']*)'\s*,?\s*$")


def read_tokens() -> dict[str, str]:
    theme = (SRC / "10-theme.js").read_text(encoding="utf-8")
    block = re.search(r"const JARVIS_TOKENS = \{(.*?)\n\}", theme, re.S)
    if not block:
        return {}
    tokens: dict[str, str] = {}
    for line in block.group(1).splitlines():
        found = TOKEN_RE.match(line)
        if found:
            tokens[found.group(1)] = found.group(2)
    return tokens


def read_css() -> str:
    """The VALUE of JARVIS_CSS: the template literal with its ${JARVIS_TOKENS.x}
    interpolations resolved. Anything else interpolated is left alone + warned."""
    theme = (SRC / "10-theme.js").read_text(encoding="utf-8")
    block = re.search(r"const JARVIS_CSS = `(.*?)`\s*$", theme, re.S)
    if not block:
        warn("JARVIS_CSS not found in 10-theme.js — mirror CSS left empty")
        return ""
    css = block.group(1)
    tokens = read_tokens()

    def swap(match: re.Match[str]) -> str:
        key = match.group(1)
        if key in tokens:
            return tokens[key]
        warn(f"unresolved ${{JARVIS_TOKENS.{key}}} in JARVIS_CSS")
        return match.group(0)

    css = re.sub(r"\$\{JARVIS_TOKENS\.([A-Za-z0-9_]+)\}", swap, css)
    leftovers = re.findall(r"\$\{[^}]+\}", css)
    if leftovers:
        warn(f"JARVIS_CSS still interpolates {sorted(set(leftovers))} — the mirror will not resolve them")
    return css


def build_mirror() -> str | None:
    template = ROOT / "dashboard" / "mirror.template.html"
    if not template.is_file():
        return None
    js_parts = []
    for name in MIRROR_PARTS:
        path = SRC / name
        if not path.is_file():
            warn(f"{name} missing — mirror.html built without it")
            continue
        body = path.read_text(encoding="utf-8")
        js_parts.append(f"\n// ─── {name} ───\n" + body)
    html = template.read_text(encoding="utf-8")
    html = html.replace("__JARVIS_THEME_CSS__", read_css())
    html = html.replace("__JARVIS_MIRROR_JS__", "".join(js_parts))
    return html


# --- write / check ----------------------------------------------------------

def outputs() -> list[tuple[Path, str]]:
    pairs: list[tuple[Path, str]] = [(ROOT / "desktop" / "plugin.js", build_plugin())]
    mirror = build_mirror()
    if mirror is not None:
        pairs.append((ROOT / "dashboard" / "mirror.html", mirror))
    return pairs


def main(argv: list[str]) -> int:
    check = "--check" in argv[1:]
    if not SRC.is_dir():
        print(f"error: {SRC} not found", file=sys.stderr)
        return 1

    stale = []
    for path, content in outputs():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if check:
            if current != content:
                stale.append(path)
            continue
        if current == content:
            print(f"unchanged  {path.relative_to(ROOT)}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote      {path.relative_to(ROOT)}  ({len(content.splitlines())} lines)")

    if check:
        if stale:
            for path in stale:
                print(f"stale: {path.relative_to(ROOT)} — run python3 scripts/build.py", file=sys.stderr)
            return 1
        print("up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
