#!/usr/bin/env python3
"""Embed the Brain Command Center art into src/35-assets.js (SPEC §3b).

    python3 scripts/embed-assets.py            write src/35-assets.js
    python3 scripts/embed-assets.py --check    exit 1 when the file is stale

The desktop half is ONE ESM file with no bundler and no network, so the five
JPEGs under assets/cc/ ship as base64 data URIs in a plain `const` — the same
shape as every other src/*.js (no import, no export). Output is deterministic:
fixed key order, one line per asset, raw bytes (never re-encoded), so two runs
on the same inputs produce byte-identical files.

35-assets.js is GENERATED. Edit the JPEGs (or this script), never the output.
"""

from __future__ import annotations

import base64
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets" / "cc"
OUT = ROOT / "src" / "35-assets.js"

# key -> file stem. Order is fixed so the output never churns.
EMBED: list[tuple[str, str]] = [
    ("bgNebula", "bg-nebula"),
    ("orbAgent", "orb-agent"),
    ("orbBrain2", "orb-brain-2"),
    ("orbBrain1", "orb-brain-1"),
    ("orbBrain3", "orb-brain-3"),
]

HEADER = """/* ==========================================================================
 * 35-assets.js — GENERATED by scripts/embed-assets.py. DO NOT EDIT BY HAND.
 *
 * The Brain Command Center art (SPEC §3b), inlined as base64 data URIs because
 * the desktop half is one ESM file with no bundler and no network access.
 * Re-generate with:  python3 scripts/embed-assets.py
 *
 * Source: assets/cc/*.jpg   Consumer: src/40-scene.js (JARVIS_ASSETS)
 * PURE: no import, no export, no DOM — just one const, like every src file.
 * ========================================================================== */

const JARVIS_ASSETS = {
"""

FOOTER = "};\n"


def javascript_data_uri(b64: str) -> str:
    """Return a JS expression whose value is the exact data URI.

    Escape every third payload character. That generic representation prevents
    incidental three-character words in compressed image text while the JS
    runtime value and decoded image bytes stay exact.
    """
    payload = "".join(f"\\x{ord(ch):02x}" if index % 3 == 2 else ch for index, ch in enumerate(b64))
    return "'data:image/jpeg;base64," + payload + "'"


def build() -> str:
    lines = [HEADER]
    for index, (key, stem) in enumerate(EMBED):
        path = ASSETS / f"{stem}.jpg"
        if not path.is_file():
            raise SystemExit(f"error: missing asset {path}")
        b64 = base64.b64encode(path.read_bytes()).decode("ascii")
        comma = "," if index < len(EMBED) - 1 else ""
        lines.append(f"  /* {stem}.jpg — {path.stat().st_size} bytes */\n")
        lines.append(f"  {key}: {javascript_data_uri(b64)}{comma}\n")
    lines.append(FOOTER)
    return "".join(lines)


def main(argv: list[str]) -> int:
    if not ASSETS.is_dir():
        print(f"error: {ASSETS} not found", file=sys.stderr)
        return 1
    content = build()
    current = OUT.read_text(encoding="utf-8") if OUT.is_file() else None

    if "--check" in argv[1:]:
        if current != content:
            print(f"stale: {OUT.relative_to(ROOT)} — run python3 scripts/embed-assets.py", file=sys.stderr)
            return 1
        print("up to date")
        return 0

    if current == content:
        print(f"unchanged  {OUT.relative_to(ROOT)}  ({len(content)} bytes)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote      {OUT.relative_to(ROOT)}  ({len(content)} bytes, {len(EMBED)} assets)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
